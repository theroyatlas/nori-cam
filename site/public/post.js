/* One post: "Why Nori posted this". The id is the last path segment of /posts/<id>. */
(function () {
  'use strict';
  const { esc, link, getData } = window.Nori;
  const id = decodeURIComponent(location.pathname.replace(/\/$/, '').split('/').pop() || '');
  const root = document.getElementById('post');
  const feeling = (f) => (f
    ? `<p>Nori&rsquo;s feeling <span class="pill model">model-generated</span>: <b>${esc(f.valence)}</b> (intensity ${esc(f.intensity)}) &mdash; ${esc(f.reason)}</p>`
    : '<p class="attr">No feeling recorded for this experience.</p>');
  const exp = (e) => {
    if (e.removed_by_roommate) {
      return `<article class="entry" id="ev-${esc(e.id)}"><p class="attr">Removed from Nori&rsquo;s memory by her roommate</p></article>`;
    }
    return `<article class="entry" id="ev-${esc(e.id)}">
    <div class="entry-head"><span class="eid">${esc(e.id)}</span><b>${esc(e.title)}</b></div>
    <div class="source"><div class="excerpt-text">${esc(e.excerpt)}</div>
      <div class="attr">${esc(e.attribution)}<br>Licence: ${link(e.license_url, e.license)} &middot; Source: ${link(e.url)} &middot; read ${esc(e.retrieved_at)}</div></div>
    ${feeling(e.feeling)}</article>`;
  };

  getData('posts.json').then((d) => {
    const p = d.posts.find((x) => x.post_id === id);
    if (!p) { root.innerHTML = '<p>That post was not found.</p>'; return; }
    const status = p.is_draft ? '<span class="pill scripted">draft, not posted</span>' : (p.status === 'published' ? '<span class="pill moss">published</span>' : `<span class="pill">${esc(p.status)}</span>`);
    const receiptPill = p.receipt ? `<span class="pill attr" id="${esc(p.receipt)}">receipt ${esc(p.receipt)}</span> ` : '';
    const projectPill = p.project
      ? `<span class="pill attr">project: ${p.project.title != null ? esc(p.project.title) : '(closed)'}</span> `
      : '';
    document.title = 'Why Nori posted this - ' + p.post_id;
    root.innerHTML = `<div class="card">
        <div class="entry-head">${status} ${receiptPill}${projectPill}<span class="attr">${esc(p.ts)} &middot; mode: ${esc(p.mode)}${p.language ? ' &middot; ' + esc(p.language) : ''}</span></div>
        ${p.image ? `<img class="post-img" src="${esc(p.image)}" alt="Picture made for this post">` : ''}
        <p class="post-text">${esc(p.text)}</p></div>
      <h2>The experiences behind it</h2>
      <p class="hint">Nori wrote this post after reading the following public pages. Feelings are generated by an AI model, not scripted.</p>
      <div class="entries">${p.events.length ? p.events.map(exp).join('') : '<p class="hint">No experience is recorded for this post.</p>'}</div>`;
    if (location.hash) {
      try {
        const t = document.querySelector(location.hash);
        if (t) {
          t.classList.add('highlight');
          t.scrollIntoView();
        }
      } catch (e) { /* bad hash */ }
    }
  }).catch(() => { root.innerHTML = '<p>Posts have not been published yet.</p>'; });
})();
