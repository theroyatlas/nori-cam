"""Write site/oneoff/r40_layout.sql: the R40 observatory world layout for the production D1, as one SQL file.

Apply it once, after migrations 0002-0004, to produce the same world app/cam/observatory_owner.py prepare_world()
produces locally: the seeded pixel-room rows are removed, the one static compound collider and the initial spawn
segment are inserted, and the world row is reset. It is a no-op when the gifts table is not empty (prepare_world's
rule) or when the R40 compound is already there. Every statement is guarded by a flag on the world row, and the
last SELECT reports which way it went.

    python -X utf8 tools/r40_layout_sql.py            # writes site/oneoff/r40_layout.sql
    python -X utf8 tools/r40_layout_sql.py --check    # exits 1 if the file is out of date
"""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.cam.observatory_owner import MODEL, layout_cells  # noqa: E402  (read-only use)

OUT = ROOT / 'site' / 'oneoff' / 'r40_layout.sql'
# Same order as prepare_world.
TABLES = ['interactions', 'object_states', 'object_cards', 'objects', 'segments', 'experiences', 'events', 'intents', 'weather']
FLAG = 'r40-layout-applying'
GUARD = f"EXISTS (SELECT 1 FROM world WHERE id=1 AND writer='{FLAG}')"
NOW = '(SELECT updated_at FROM world WHERE id=1)'


def q(value):
    return "'" + str(value).replace("'", "''") + "'"


def card_for(name, height):
    # Identical to the card prepare_world writes.
    return {'name': name, 'category': 'furniture', 'size': 'L', 'height': 'low', 'tags': [], 'sensations': {}, 'parts': [], 'states': ['default'], 'hazards': [],
            'space': {'cm': {'w': 40, 'd': 40, 'h': max(1, round(height * 100))}, 'blocks': True, 'placement': 'floor', 'movable': {'push': False, 'rotate': False, 'stack': False}, 'state_cm': {}},
            'affordances': [], 'beyond_executor': ['custom furniture climbing not part of this floor-only photo test'], 'summary': 'R40 conservative static room collider'}


def build_sql():
    contract = json.loads((MODEL / 'room-contract.json').read_text())
    items, spawn, checks = layout_cells(contract)
    lines = [
        '-- Generated by tools/r40_layout_sql.py from site/observatory/model/room-contract.json. Do not edit by hand.',
        '-- R40 observatory layout for a world freshly seeded by migrations 0002-0004 (same result as',
        '-- app/cam/observatory_owner.py prepare_world). No-op when any gift exists or the R40 compound is already there.',
        f'-- layout checks: {json.dumps(checks)}',
        '',
        '-- 1. Claim the world row only when no gift exists and the layout is not applied yet; every later statement needs the claim.',
        f"UPDATE world SET writer='{FLAG}', updated_at=CAST(strftime('%s','now') AS INTEGER)*1000 WHERE id=1"
        " AND NOT EXISTS (SELECT 1 FROM gifts) AND NOT EXISTS (SELECT 1 FROM objects WHERE id='r40_static_compound');",
        '-- 2. Remove the seeded pixel-room world.',
    ]
    lines += [f'DELETE FROM {table} WHERE {GUARD};' for table in TABLES]
    lines.append('-- 3. The static room compound (cells Nori cannot enter) and its card.')
    for ident, name, cells, height in items:
        x, y = min(cells)
        foot = [[a - x, b - y] for a, b in cells]
        card_id = 'card:' + ident
        card = json.dumps(card_for(name, height))
        lines.append(f'INSERT INTO object_cards(id,object_id,created_at,source,card) SELECT {q(card_id)},{q(ident)},{NOW},{q("prefab")},{q(card)} WHERE {GUARD};')
        lines.append('INSERT INTO objects(id,kind,tags,size,x,y,z,footprint,rotation,blocks,placement,status,state,sprite,card_id,origin,created_at) '
                     f"SELECT {q(ident)},'r40_static','[]','L',{x},{y},0,{q(json.dumps(foot))},0,1,'floor','placed','default','procedural:room_collider',{q(card_id)},"
                     f"{q(json.dumps({'type': 'r40_layout'}))},{NOW} WHERE {GUARD};")
        lines.append('INSERT INTO object_states(object_id,valid_from,x,y,z,footprint,rotation,status,state,sprite,cause) '
                     f"SELECT {q(ident)},{NOW},{x},{y},0,{q(json.dumps(foot))},0,'placed','default','procedural:room_collider','r40-layout-bootstrap' WHERE {GUARD};")
    lines.append('-- 4. Initial spawn segment: Nori sits at the spawn cell for one second, then the Worker plans as usual.')
    lines.append("INSERT INTO segments(start_at,end_at,action,primitive,pose,facing,path,z,effects,source,debug,world_version) "
                 f"SELECT {NOW},{NOW}+1000,'idle','wait','sit',1,{q(json.dumps([list(spawn)]))},0,'[]','safe',{q(json.dumps({'initial_room_spawn': True}))},0 WHERE {GUARD};")
    lines.append('-- 5. Reset the world row and release the claim (same values prepare_world writes).')
    lines.append("UPDATE world SET version=0, writer='observatory-bootstrap', timeline_until=updated_at+1000,"
                 " state_json=json_set(state_json,'$.settled_through',updated_at,'$.nori.z',0)"
                 f" WHERE id=1 AND writer='{FLAG}';")
    lines.append("SELECT CASE WHEN EXISTS (SELECT 1 FROM objects WHERE id='r40_static_compound') AND (SELECT COUNT(*) FROM objects WHERE id NOT LIKE 'r40_%' AND origin NOT LIKE '%gift%')=0"
                 " THEN 'r40 layout present' ELSE 'r40 layout NOT applied (gifts present or seed world kept)' END AS r40_layout,"
                 " (SELECT COUNT(*) FROM gifts) AS gifts, (SELECT COUNT(*) FROM objects) AS objects, (SELECT COUNT(*) FROM segments) AS segments;")
    return '\n'.join(lines) + '\n'


def main():
    sql = build_sql()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != sql:
            raise SystemExit(f'{OUT} is out of date; run python -X utf8 tools/r40_layout_sql.py')
        print('up to date')
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding='utf-8', newline='\n')
    print(OUT)


if __name__ == '__main__':
    main()
